/** Where an unmapped source of `srcChannels` on the wire plays in a mix `mixChannels` wide: the
 *  table, or channel for channel at equal widths and from an 8-channel wire (GStreamer leaves it
 *  unpositioned and converts it to no other width). A gain only where it is not 1. */
export function default302mChannelMap(srcChannels: number, mixChannels: number): ChannelMapEntry[] {
    const src = Math.trunc(srcChannels);
    const dst = Math.max(1, Math.min(8, Math.trunc(mixChannels) || 1));
    const table = GST_DEFAULT[`${src}/${dst}`];
    if (!table) {
        return Array.from({ length: Math.min(src, dst) }, (_, i) => ({
            srcChannel: i,
            dstChannel: i,
        }));
    }
    return table.flatMap((row, dstChannel) =>
        row.flatMap((gain, srcChannel) =>
            gain === 0 ? [] : [{ srcChannel, dstChannel, ...(gain === 1 ? {} : { gain }) }],
        ),
    );
}
