/** The default map of a source `srcChannels` wide on the wire (`wire302mChannels`) into a mix
 *  `dstChannels` wide: the table, or channel for channel at equal widths and from 8 channels. */
export function default302mMap(
    srcChannels: number,
    dstChannels: number,
): Array<{ srcChannel: number; dstChannel: number; gain: number }> {
    const dst = Math.max(1, Math.min(8, Math.trunc(dstChannels) || 1));
    const table = GST_DEFAULT[`${srcChannels}/${dst}`];
    if (!table) {
        return Array.from({ length: Math.min(srcChannels, dst) }, (_, i) => ({
            srcChannel: i,
            dstChannel: i,
            gain: 1,
        }));
    }
    return table.flatMap((row, dstChannel) =>
        row.flatMap((gain, srcChannel) => (gain === 0 ? [] : [{ srcChannel, dstChannel, gain }])),
    );
}

/** A gain as an operator reads it: "−6.0 dB"; unity is "0 dB". */
export function gainDb(gain: number): string {
    if (gain === 1) return '0 dB';
    if (gain <= 0) return 'muted';
    return `${(20 * Math.log10(gain)).toFixed(1).replace('-', '−')} dB`;
}
